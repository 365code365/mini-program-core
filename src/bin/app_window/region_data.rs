/// 第 pi 个省的市名列表
pub fn cities_of(pi: usize) -> Vec<String> {
    PROVINCES
        .get(pi)
        .map(|(_, cities)| cities.iter().map(|(c, _)| c.to_string()).collect())
        .unwrap_or_default()
}

/// 第 pi 个省、第 ci 个市的区名列表
pub fn districts_of(pi: usize, ci: usize) -> Vec<String> {
    PROVINCES
        .get(pi)
        .and_then(|(_, cities)| cities.get(ci))
        .map(|(_, districts)| districts.iter().map(|d| d.to_string()).collect())
        .unwrap_or_default()
}
