const WISH_KEY = 'tv_wish';

function guideOf(name) {
  const g = GUIDE[name] || ['春秋两季', 3, 450, '到达后以公共交通 + 打车为主', '当地特色小吃'];
  return { season: g[0], days: g[1], cost: g[2], traffic: g[3], food: g[4] };
}
function wishes() { return wx.getStorageSync(WISH_KEY) || []; }
function isWish(name) { return wishes().indexOf(name) >= 0; }
function toggleWish(name) {
  const list = wishes();
  const i = list.indexOf(name);
  if (i >= 0) list.splice(i, 1); else list.unshift(name);
  wx.setStorageSync(WISH_KEY, list);
  return i < 0;
}

module.exports = { guideOf, wishes, isWish, toggleWish };
