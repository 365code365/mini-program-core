const LIST = RAW.map(r => ({
  id: r[0], name: r[1], cat: r[2], minutes: r[3], level: r[4], kcal: r[5], tags: r[6], c1: r[7], c2: r[8],
  base: 2,
  ingredients: r[9].map(x => ({ name: x[0], amount: x[1], unit: x[2] })),
  steps: r[10].map((x, i) => ({ no: i + 1, text: x[0], sec: x[1] })),
  catText: CATS.find(c => c.key === r[2]).text,
  initial: r[1].charAt(0)
}))
function byId(id) {
  return LIST.find(r => r.id === Number(id)) || null
}
function byCat(key) {
  return key === 'all' ? LIST : LIST.filter(r => r.cat === key)
}
// 分页：第 page 页（从 0 开始），每页 size 条
function page(key, p, size) {
  const all = byCat(key)
  return { list: all.slice(p * size, (p + 1) * size), total: all.length }
}
// 关键词：菜名、标签、食材都算
function search(kw) {
  kw = (kw || '').trim()
  if (!kw) return []
  return LIST.filter(r => r.name.indexOf(kw) >= 0 || r.tags.indexOf(kw) >= 0 || r.ingredients.some(i => i.name.indexOf(kw) >= 0))
}
// 份量换算：保留一位小数，整数不带 .0
function scale(amount, base, servings) {
  const v = Math.round((amount * servings / base) * 10) / 10
  return String(v)
}
module.exports = { CATS, HOT_TAGS, LIST, byId, byCat, page, search, scale }
