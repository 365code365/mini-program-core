// 条款（rich-text 的 nodes 用 HTML 字符串）与常见问题，按产品的险种、等待期拼出来。
const SHORT = { medical: 1, child: 1, accident: 1, travel: 1, cancer: 1, outpatient: 1 };

function clauses(p) {
  const shortTerm = !!SHORT[p.model];
  const list = [];
  list.push('<p><strong>第一条　投保范围</strong>　凡投保时年龄在 ' + p.ages[0] + ' 周岁至 ' + p.ages[1] +
    ' 周岁之间、符合本公司健康告知要求的人士，可作为被保险人参加本保险。被保险人本人、对被保险人有保险利益的其他人可作为投保人。</p>');
  list.push('<p><strong>第二条　等待期</strong>　' + (p.wait > 0
    ? '自本合同生效日起 <span style="color:#f0524a">' + p.wait + ' 日</span>内为等待期。等待期内因疾病发生保险事故的，本公司不承担保险责任；因意外伤害发生保险事故的不受等待期限制。续保不再设等待期。'
    : '本合同不设等待期，自保单载明的生效日零时起开始承担保险责任。') + '</p>');
  list.push('<p><strong>第三条　责任免除</strong>　因下列情形之一导致保险事故的，本公司不承担保险责任：（一）投保人对被保险人的故意杀害、故意伤害；' +
    '（二）被保险人故意犯罪或抗拒依法采取的刑事强制措施；（三）被保险人主动吸食或注射毒品；（四）被保险人酒后驾驶、无合法有效驾驶证驾驶；' +
    '（五）战争、军事冲突、暴乱或武装叛乱；（六）核爆炸、核辐射或核污染' + (p.model === 'accident' ? '；（七）被保险人从事潜水、跳伞、攀岩等高风险运动。' : '；（七）投保前已患有且未如实告知的疾病。') + '</p>');
  list.push('<p><strong>第四条　犹豫期</strong>　' + (shortTerm
    ? '本合同为一年期（或短期）保险，自签收电子保单之日起 15 日内退保的，本公司全额退还已交保险费；超过 15 日退保的，按未满期净保费退还。'
    : '自您签收本合同次日起有 15 日的犹豫期。犹豫期内解除合同的，本公司扣除不超过 10 元的工本费后无息退还已交保险费；犹豫期后解除合同的，退还现金价值，可能会有一定损失。') + '</p>');
  list.push('<p><strong>第五条　' + (shortTerm ? '续保' : '保险费的支付') + '</strong>　' + (p.model === 'medical'
    ? '本产品保证续保期间为 20 年，保证续保期间内，即使被保险人健康状况变化或发生理赔，本公司也不会因此拒绝续保，但费率可能随年龄调整。'
    : shortTerm ? '保险期间届满前，经本公司审核同意，您可申请续保，续保时按届时的费率与条款执行。'
      : '分期交付保险费的，在交付首期保险费后，您应在每个保险费约定支付日交纳其余各期保险费；逾期未交的，自约定支付日次日零时起 60 日为宽限期。') + '</p>');
  list.push('<p><strong>第六条　如实告知</strong>　订立本合同时，本公司会就被保险人的有关情况提出询问，您应当如实告知。' +
    '您故意或因重大过失未履行如实告知义务、足以影响本公司决定是否同意承保或者提高保险费率的，本公司有权解除本合同。</p>');
  return list;
}

function faqs(p) {
  const list = [];
  if (p.model === 'medical' || p.model === 'child') {
    list.push({ q: '有社保和没社保保费一样吗？', a: '投保时保费相同；但没有使用社保结算的费用按 60% 赔付，建议就医时先走社保结算再申请理赔。' });
    list.push({ q: '1 万免赔额怎么算？', a: '一个保单年度内累计计算，社保报销、其他商业保险已赔付的部分可以抵扣免赔额；重大疾病医疗费用不设免赔额。' });
  }
  if (p.model === 'critical' || p.model === 'cancer') {
    list.push({ q: '确诊后多久能拿到赔款？', a: '材料齐全后，10 万元以下案件一般 3 个工作日内结案，10 万元以上不超过 30 日；赔款直接打入您指定的银行账户。' });
    list.push({ q: '保终身和保至 70 岁怎么选？', a: '保终身保障更完整但保费约高 50%；预算有限可先选保至 70 岁，用省下的保费提高保额，70 岁后的风险用防癌险补充。' });
  }
  if (p.model === 'accident') {
    list.push({ q: '高风险职业能买吗？', a: '本产品承保 1~4 类职业；5~6 类职业（如高空作业、井下作业）暂不承保，请选择专属的职业意外险。' });
    list.push({ q: '骑电动车摔伤能赔吗？', a: '能赔意外医疗；如电动车属于机动车范畴而您无合法驾驶证，则不承担伤残、身故责任。' });
  }
  if (p.model === 'life') {
    list.push({ q: '定期寿险适合谁？', a: '家庭经济支柱，尤其是有房贷、车贷或子女尚未独立的人群。保额建议覆盖 5~10 年家庭开支加上未还清的负债。' });
  }
  if (p.model === 'travel') {
    list.push({ q: '可以用于办理申根签证吗？', a: '可以。境外医疗保额 30 万元及以上的计划均满足申根签证要求，投保后可下载中英文电子保单。' });
    list.push({ q: '已经出境了还能买吗？', a: '本产品须在出境前投保，保险期间自出境时开始，入境时结束。' });
  }
  if (p.model === 'outpatient') {
    list.push({ q: '在药店买药能报吗？', a: '凭二级及以上公立医院开具的处方，在合作药店购药的费用可以报销；无处方的自购药品不予报销。' });
  }
  list.push({ q: '健康告知有异常还能投保吗？', a: '部分情况可以走人工核保，提交近两年的体检报告或病历后，3 个工作日内给出标准体、除外承保或加费承保的结论。' });
  list.push({ q: '怎么申请理赔？', a: '在「保单」页选择对应保单，点「申请理赔」上传发票、病历等材料，进度可在「我的 - 理赔记录」随时查看。' });
  return list;
}

module.exports = { clauses, faqs };
