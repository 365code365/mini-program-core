function pad(n) {
  return n < 10 ? '0' + n : '' + n;
}
function dateStr(ts) {
  const d = new Date(ts);
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

