const NUM = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十']

// 「第二十三章」
function cn(n) {
  if (n <= 10) return NUM[n]
  if (n < 20) return '十' + NUM[n - 10]
  const t = Math.floor(n / 10)
  const u = n % 10
  return NUM[t] + '十' + (u ? NUM[u] : '')
}

const TITLES = ['初见', '残页', '夜雨', '旧约', '回声', '迷雾', '远行', '归途', '灯火', '长夜', '破晓', '故人']

function get(id) {
  return BOOKS.find(b => b.id === id) || null
}

function chapterTitle(book, i) {
  return '第' + cn(i + 1) + '章 ' + TITLES[(i * 5 + book.id.charCodeAt(1)) % TITLES.length]
}

function catalog(book) {
  const list = []
  for (let i = 0; i < book.chapters; i++) list.push({ index: i, title: chapterTitle(book, i) })
  return list
}

// 一章 18 段，每段由 3 句素材拼成（按章号、段号挑句子）
function content(book, i) {
  const p = book.pool
  const paras = []
  for (let k = 0; k < 18; k++) {
    const a = p[(i * 7 + k * 3) % p.length]
    const b = p[(i * 3 + k * 5 + 1) % p.length]
    const c = p[(i + k * 2 + 2) % p.length]
    paras.push(a + b + c)
  }
  return paras
}

