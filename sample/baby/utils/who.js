function at(row, month) {
  const m = Math.max(0, Math.min(24, month));
  for (let i = 1; i < MONTHS.length; i++) {
    if (m <= MONTHS[i]) {
      const t = (m - MONTHS[i - 1]) / (MONTHS[i] - MONTHS[i - 1]);
      return row[i - 1] + (row[i] - row[i - 1]) * t;
    }
  }
  return row[row.length - 1];
}

// 某月龄下各百分位的值
function bands(sex, metric, month) {
  return TABLE[sex === 'girl' ? 'girl' : 'boy'][metric].map((row) => at(row, month));
}

// 落在哪一段：返回 { text, level }，level: low / normal / high
function evaluate(sex, metric, month, value) {
  const b = bands(sex, metric, month);
  const v = Number(value);
  if (v < b[0]) return { text: '低于 P3，建议咨询儿保医生', level: 'low' };
  if (v > b[4]) return { text: '高于 P97，建议咨询儿保医生', level: 'high' };
  for (let i = 0; i < 4; i++) {
    if (v <= b[i + 1]) return { text: '处于 ' + P[i] + '~' + P[i + 1] + ' 之间，' + (i === 0 || i === 3 ? '在正常范围内' : '发育良好'), level: 'normal' };
  }
  return { text: '', level: 'normal' };
}

